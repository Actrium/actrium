#!/bin/bash

# ==============================================================================
# TestFlight Configure Check Scripts
# ==============================================================================

set -e

# Colour Output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}===================================================${NC}"
echo -e "${BLUE}🔍 TestFlight Configure Check${NC}"
echo -e "${BLUE}===================================================${NC}"
echo ""

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_ROOT"

ERRORS=0
WARNINGS=0

check_ok() {
    echo -e "${GREEN}✅ $1${NC}"
}

check_warning() {
    echo -e "${YELLOW}⚠️  $1${NC}"
    WARNINGS=$((WARNINGS + 1))
}

check_error() {
    echo -e "${RED}❌ $1${NC}"
    ERRORS=$((ERRORS + 1))
}

echo "📋 Check essential tools..."
echo ""

# Inspection Xcode
if command -v xcodebuild &> /dev/null; then
    XCODE_VERSION=$(xcodebuild -version | head -n 1)
    check_ok "Xcode: $XCODE_VERSION"
else
    check_error "Xcode Not installed"
fi

# Inspection xcpretty
if command -v xcpretty &> /dev/null; then
    check_ok "xcpretty Installed"
else
    check_warning "xcpretty Not installed (Optional, for beautification output)"
    echo "          Install: gem install xcpretty"
fi

# Inspection CocoaPods
if command -v pod &> /dev/null; then
    POD_VERSION=$(pod --version)
    check_ok "CocoaPods: $POD_VERSION"
else
    check_error "CocoaPods Not installed"
    echo "          Install: sudo gem install cocoapods"
fi

# Inspection bun
if command -v bun &> /dev/null; then
    BUN_VERSION=$(bun --version)
    check_ok "bun: $BUN_VERSION"
else
    check_warning "bun Not installed (script automatically installed)"
    echo "          Manually Install: curl -fsSL https://bun.com/install | bash"
fi

# Inspection agvtool
if command -v agvtool &> /dev/null; then
    check_ok "agvtool Installed"
else
    check_error "agvtool Not installed"
fi

echo ""
echo "📁 Check Project Files..."
echo ""

# Inspection Workspace
if [ -f "Actrium.xcworkspace/contents.xcworkspacedata" ]; then
    check_ok "Workspace Existence"
else
    check_error "Actrium.xcworkspace Cannot initialise Evolution's mail component."
fi

# Inspection Pods
if [ -d "Pods" ]; then
    check_ok "CocoaPods Reliance installed"
else
    check_warning "CocoaPods Dependence on uninstalled"
    echo "          Run: pod install"
fi

# Inspection ActriumRuntime symlink
if [ -L "ActriumRuntime" ] && [ -d "ActriumRuntime" ]; then
    check_ok "ActriumRuntime symlink Configured"
elif [ -e "ActriumRuntime" ]; then
    check_error "ActriumRuntime It exists, but it doesn't work. symlink"
else
    check_warning "ActriumRuntime symlink Not created"
    echo "          Run: ./Scripts/ensure-actrium-runtime.sh"
fi

# Inspection React Native Dependency
if [ -d "ActriumRuntime/node_modules" ]; then
    check_ok "React Native Reliance installed"
else
    check_warning "React Native Dependence on uninstalled"
    echo "          Run: cd ActriumRuntime && bun install"
fi

# Inspection ExportOptions.plist
if [ -f "Scripts/ExportOptions.plist" ]; then
    check_ok "ExportOptions.plist Existence"

    # Check to include YOUR_TEAM_ID
    if grep -q "YOUR_TEAM_ID" "Scripts/ExportOptions.plist"; then
        check_warning "ExportOptions.plist Include placeholder YOUR_TEAM_ID"
        echo "          Please change to actual. Team ID"
    fi
else
    check_warning "ExportOptions.plist It doesn't exist. It'll be. build/upload , which is generated by environment variable"
fi

echo ""
echo "🔐 Check authentication configuration..."
echo ""

# Inspection API Key Configure
if [ -n "$APP_STORE_CONNECT_API_KEY_PATH" ]; then
    if [ -f "$APP_STORE_CONNECT_API_KEY_PATH" ]; then
        check_ok "API Key File Exists"
    else
        check_error "API Key File path configuration but file does not exist: $APP_STORE_CONNECT_API_KEY_PATH"
    fi

    if [ -n "$APP_STORE_CONNECT_API_KEY_ID" ]; then
        check_ok "API Key ID Configured"
    else
        check_warning "APP_STORE_CONNECT_API_KEY_ID Not set"
    fi

    if [ -n "$APP_STORE_CONNECT_API_ISSUER_ID" ]; then
        check_ok "API Issuer ID Configured"
    else
        check_warning "APP_STORE_CONNECT_API_ISSUER_ID Not set"
    fi
elif [ -n "$APPLE_ID" ]; then
    check_ok "Apple ID Configured: $APPLE_ID"
    check_warning "Recommended App Store Connect API Key Not Apple ID"
else
    check_warning "No Uploader Configured (API Key or Apple ID)"
    echo "          Please, take your time. Scripts/TESTFLIGHT_README.md Configure"
fi

echo ""
echo "🎯 Check Project Configuration..."
echo ""

# Get Version Information
if command -v agvtool &> /dev/null; then
    VERSION=$(agvtool what-marketing-version -terse1 2>/dev/null || echo "N/A")
    BUILD=$(agvtool what-version -terse 2>/dev/null || echo "N/A")

    echo "   Version Number: $VERSION"
    echo "   Build: $BUILD"
    echo ""
fi

# Inspection Team ID
TEAM_ID=$(grep -A 1 "DEVELOPMENT_TEAM" Actrium.xcodeproj/project.pbxproj | grep "=" | head -n 1 | cut -d'"' -f2 || echo "")
if [ -n "$TEAM_ID" ] && [ "$TEAM_ID" != "" ]; then
    check_ok "Team ID: $TEAM_ID"
else
    check_warning "Team ID Not configured in project"
fi

# Inspection Bundle ID
BUNDLE_ID=$(grep -A 1 "PRODUCT_BUNDLE_IDENTIFIER" Actrium.xcodeproj/project.pbxproj | grep "=" | head -n 1 | cut -d'"' -f2 || echo "")
if [ -n "$BUNDLE_ID" ] && [ "$BUNDLE_ID" != "" ]; then
    check_ok "Bundle ID: $BUNDLE_ID"
else
    check_warning "Bundle ID Not configured in project"
fi

echo ""
echo "===================================================="
echo ""

if [ $ERRORS -eq 0 ] && [ $WARNINGS -eq 0 ]; then
    echo -e "${GREEN}🎉 All checks are through! You can run the upload script.${NC}"
    echo ""
    echo "Run: ./Scripts/upload-testflight.sh"
elif [ $ERRORS -eq 0 ]; then
    echo -e "${YELLOW}⚠️  Yes. $WARNINGS A warning. Recommend repair and upload.${NC}"
    echo ""
    echo "If you need to continue: ./Scripts/upload-testflight.sh"
else
    echo -e "${RED}❌ Yes. $ERRORS One mistake, please fix it first.${NC}"
    echo ""
    echo "Please, take your time.: Scripts/TESTFLIGHT_README.md"
    exit 1
fi

echo ""
echo "💡 Hint:"
echo "   - First upload proposal first run: ./Scripts/test-build.sh"
echo "   - View Detailed Documents: Scripts/TESTFLIGHT_README.md"
echo "   - Environmental Variable Configuration: Scripts/.env.example"
echo ""
