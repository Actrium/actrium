fn quote_ts(value: &str) -> String {
    let mut quoted = String::with_capacity(value.len());

    for ch in value.chars() {
        match ch {
            '\\' => quoted.push_str("\\\\"),
            '\'' => quoted.push_str("\\'"),
            '\n' => quoted.push_str("\\n"),
            '\r' => quoted.push_str("\\r"),
            '\t' => quoted.push_str("\\t"),
            ch if ch.is_ascii() && !ch.is_ascii_control() => quoted.push(ch),
            ch => {
                let code_point = ch as u32;
                if code_point <= 0xffff {
                    quoted.push_str(&format!("\\u{code_point:04X}"));
                } else {
                    let scalar = code_point - 0x1_0000;
                    let high = 0xd800 + (scalar >> 10);
                    let low = 0xdc00 + (scalar & 0x3ff);
                    quoted.push_str(&format!("\\u{high:04X}\\u{low:04X}"));
                }
            }
        }
    }

    quoted
}

fn json_string(value: &str) -> String {
    serde_json::to_string(value).expect("TypeScript string literal must serialize")
}

fn json_sql(value: &str) -> String {
    json_string(value.trim())
}

fn quote_property(value: &str) -> String {
    if value
        .chars()
        .all(|ch| ch == '_' || ch == '$' || ch.is_ascii_alphanumeric())
        && !value
            .chars()
            .next()
            .map(|ch| ch.is_ascii_digit())
            .unwrap_or(true)
    {
        value.to_string()
    } else {
        format!("'{}'", quote_ts(value))
    }
}
