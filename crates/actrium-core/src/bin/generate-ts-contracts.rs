fn main() {
    let output_path = env::args_os().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from("packages/actrium/src/actr-host/generated/actroCoreContract.ts")
    });

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent).expect("failed to create generated TypeScript directory");
    }

    fs::write(&output_path, render_typescript())
        .unwrap_or_else(|err| panic!("failed to write {}: {err}", output_path.display()));
}

