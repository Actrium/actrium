use std::{env, fs, path::PathBuf};

use actrium_core::{persistence, runtime_persistence};

fn main() {
    let output_path = env::args_os().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from(
            "android/android/app/src/main/java/io/actrium/app/generated/ActriumAndroidPersistenceContract.kt",
        )
    });

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent).expect("failed to create generated Android contract directory");
    }

    fs::write(&output_path, render_kotlin())
        .unwrap_or_else(|err| panic!("failed to write {}: {err}", output_path.display()));
}

fn render_kotlin() -> String {
    use persistence::android::active_list as active;

    format!(
        r#"package io.actrium.app.generated

// Generated by crates/actrium-core/src/bin/generate-android-contracts.rs.
// Do not edit by hand. Run scripts/actrium/build-actrium-rust-bindings.sh android.

object ActriumAndroidPersistenceContract {{
    const val DATABASE_NAME = "{database_name}"
    const val DATABASE_VERSION = {database_version}

    object ActiveList {{
        const val TABLE = "{active_table}"

        object Column {{
            const val ID = "{active_column_id}"
            const val NAME = "{active_column_name}"
            const val ICON = "{active_column_icon}"
            const val SCREENSHOT = "{active_column_screenshot}"
            const val HAS_UNREAD = "{active_column_has_unread}"
            const val URL = "{active_column_url}"
            const val IS_MARKED = "{active_column_is_marked}"
            const val STATUS = "{active_column_status}"
            const val SORT_ORDER = "{active_column_sort_order}"
        }}

        object Query {{
            const val SELECT_ALL_ORDERED_BY_SORT_ORDER = "{active_query_select_all}"
            const val DELETE_ALL = "{active_query_delete_all}"
            const val COUNT_ALL = "{active_query_count_all}"
        }}
    }}

    object Runtime {{
        const val DATABASE_NAME = "{runtime_database_name}"
        const val DATABASE_VERSION = {runtime_database_version}

        object Auth {{
            const val TABLE = "{runtime_auth_table}"

            object Query {{
                const val SELECT_TOKEN_BY_ENV = "{runtime_auth_query_select_token_by_env}"
                const val UPSERT_TOKEN = "{runtime_auth_query_upsert_token}"
                const val DELETE_TOKEN_BY_ENV = "{runtime_auth_query_delete_token_by_env}"
            }}
        }}
    }}
}}
"#,
        database_name = quote_kotlin(persistence::android::DATABASE_NAME),
        database_version = persistence::android::DATABASE_VERSION,
        active_table = quote_kotlin(active::TABLE_NAME),
        active_column_id = quote_kotlin(active::column::ID),
        active_column_name = quote_kotlin(active::column::NAME),
        active_column_icon = quote_kotlin(active::column::ICON),
        active_column_screenshot = quote_kotlin(active::column::SCREENSHOT),
        active_column_has_unread = quote_kotlin(active::column::HAS_UNREAD),
        active_column_url = quote_kotlin(active::column::URL),
        active_column_is_marked = quote_kotlin(active::column::IS_MARKED),
        active_column_status = quote_kotlin(active::column::STATUS),
        active_column_sort_order = quote_kotlin(active::column::SORT_ORDER),
        active_query_select_all = quote_kotlin(active::query::SELECT_ALL_ORDERED_BY_SORT_ORDER),
        active_query_delete_all = quote_kotlin(active::query::DELETE_ALL),
        active_query_count_all = quote_kotlin(active::query::COUNT_ALL),
        runtime_database_name = quote_kotlin(runtime_persistence::RUNTIME_DATABASE_NAME),
        runtime_database_version = runtime_persistence::RUNTIME_DB_SCHEMA_VERSION,
        runtime_auth_table = quote_kotlin(runtime_persistence::table::AUTH),
        runtime_auth_query_select_token_by_env =
            quote_kotlin(runtime_persistence::query::auth::SELECT_TOKEN_BY_ENV),
        runtime_auth_query_upsert_token =
            quote_kotlin(runtime_persistence::query::auth::UPSERT_TOKEN),
        runtime_auth_query_delete_token_by_env =
            quote_kotlin(runtime_persistence::query::auth::DELETE_TOKEN_BY_ENV),
    )
}

fn quote_kotlin(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
}
